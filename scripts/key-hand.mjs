// Keys the blue chroma background AND the blue phone screen out of scripts/.raw/hand-phone-raw.png,
// darkens the hand toward a silhouette (highlights kept), crops to the subject, and measures the
// screen opening so the live UI can sit exactly behind it.
// Output: public/img/hand/hand-phone.webp (with alpha) + src/components/phone/hand-screen.ts
import { mkdirSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const SRC = new URL("./.raw/hand-phone-raw.png", import.meta.url).pathname;
const OUT_IMG = new URL("../public/img/hand/hand-phone.webp", import.meta.url).pathname;
const OUT_TS = new URL("../src/components/phone/hand-screen.ts", import.meta.url).pathname;

const { data, info } = await sharp(SRC).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const { width: W, height: H } = info;
const px = (x, y) => (y * W + x) * 4;

// 1. Key: alpha from how much blue dominates. Spill removed by clamping blue to the other channels.
const LO = 35, HI = 150;
for (let i = 0; i < data.length; i += 4) {
  const r = data[i], g = data[i + 1], b = data[i + 2];
  const d = b - Math.max(r, g);
  const a = 1 - Math.min(1, Math.max(0, (d - LO) / (HI - LO)));
  data[i + 2] = Math.min(b, Math.max(r, g) + 6);
  // 2. Silhouette curve on luminance: midtones (skin) sink, rim light and the frame stay bright.
  const l = (0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2]) / 255;
  const k = l > 0 ? Math.pow(l, 2.1) / l : 0;
  data[i] = Math.round(data[i] * k);
  data[i + 1] = Math.round(data[i + 1] * k);
  data[i + 2] = Math.round(data[i + 2] * k);
  data[i + 3] = Math.round(a * 255);
}

// 3. Screen opening: from the phone's centre, walk out until we hit the opaque frame.
const alphaAt = (x, y) => data[px(x, y) + 3];
const opaque = (x, y) => alphaAt(x, y) > 128;
// Centre of the phone: the transparent hole closest to the image centre surrounded by frame.
let cx = Math.round(W / 2), cy = Math.round(H * 0.45);
const walk = (x, y, dx, dy) => { while (x > 0 && y > 0 && x < W - 1 && y < H - 1 && !opaque(x, y)) { x += dx; y += dy; } return dx ? x : y; };
let left = walk(cx, cy, -1, 0), right = walk(cx, cy, 1, 0);
cx = Math.round((left + right) / 2);
const top = walk(cx, cy, 0, -1), bottom = walk(cx, cy, 0, 1);
cy = Math.round((top + bottom) / 2);
left = walk(cx, cy, -1, 0); right = walk(cx, cy, 1, 0);
// Corner radius: how far in from the left edge the opening starts on a row just below the top.
const probeY = top + 2;
const rowStart = walk(cx, probeY, -1, 0);
const radius = Math.max(8, rowStart - left + 4);
const screen = { left: left + 1, top: top + 1, right: right - 1, bottom: bottom - 1, radius };

// Fill the hole fully transparent (the key leaves faint noise in it).
for (let y = screen.top; y <= screen.bottom; y++)
  for (let x = screen.left; x <= screen.right; x++) {
    const i = px(x, y);
    if (data[i + 3] < 200) data[i + 3] = 0;
  }

// 4. Crop to the subject (alpha bbox) with a little air.
let minX = W, minY = H, maxX = 0, maxY = 0;
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (alphaAt(x, y) > 24) {
  if (x < minX) minX = x; if (x > maxX) maxX = x; if (y < minY) minY = y; if (y > maxY) maxY = y;
}
const pad = 8;
minX = Math.max(0, minX - pad); minY = Math.max(0, minY - pad); maxX = Math.min(W - 1, maxX + pad); maxY = H - 1; // wrist exits the bottom
const cw = maxX - minX + 1, ch = maxY - minY + 1;

mkdirSync(new URL("../public/img/hand/", import.meta.url).pathname, { recursive: true });
mkdirSync(new URL("../src/components/phone/", import.meta.url).pathname, { recursive: true });
await sharp(data, { raw: { width: W, height: H, channels: 4 } })
  .extract({ left: minX, top: minY, width: cw, height: ch })
  .webp({ quality: 86, alphaQuality: 90 })
  .toFile(OUT_IMG);

const pct = (v, total) => +((v / total) * 100).toFixed(3);
const rect = {
  aspect: +(cw / ch).toFixed(4),
  left: pct(screen.left - minX, cw),
  top: pct(screen.top - minY, ch),
  width: pct(screen.right - screen.left, cw),
  height: pct(screen.bottom - screen.top, ch),
  radius: pct(screen.radius, screen.right - screen.left), // % of screen width
};
writeFileSync(
  OUT_TS,
  `// Generated by scripts/key-hand.mjs. Screen opening of /img/hand/hand-phone.webp, in % of the image box.\nexport const HAND_SCREEN = ${JSON.stringify(rect, null, 2)} as const;\n`
);
console.log({ size: [cw, ch], screen, rect });
